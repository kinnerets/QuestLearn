depth_qs_sql = "insert into questions_bank (topic_id, type, difficulty, source, verification_status, payload) values\n"
depth_qs_sql += ",\n".join(
    f"  ('{tid}','multiple_choice',{diff},'curated','auto_passed',\n   {q(payload)})"
    for (tid, diff, payload) in DEPTH_Q
) + ";"

# all topic ids that this pack owns → clear their old questions for a clean re-run
all_ids = []
for blk in (enr_topics, sea_topics):
    all_ids += re.findall(r"'([0-9a-f]{8}-[0-9a-f-]+)'", blk)
all_ids += [t[0] for t in DEPTH_TOPICS]
ids_sql = ",\n  ".join(f"'{i}'" for i in all_ids)

out = f"""-- ══════════════════════════════════════════════════════════════════════
-- QuestLearn · content pack (run ONCE in the Supabase SQL editor).
-- Fixes the subject CHECK constraint that was rejecting the new subjects,
-- then loads: 5 enrichment domains · seasonal content · depth sub-topics.
-- Safe to re-run: question rows for these topics are cleared first.
-- ══════════════════════════════════════════════════════════════════════

-- 1. The table had a CHECK that only allowed the original subjects, so
--    'seasonal'/'economics'/… were rejected. Drop it — the app owns the list.
alter table curriculum_topics drop constraint if exists curriculum_topics_subject_check;

-- 2. Column used to lock sensitive subjects from the child's map.
alter table curriculum_topics add column if not exists parent_locked boolean not null default false;

-- 3. Topics (upserts) ─────────────────────────────────────────────────
{enr_topics}

{sea_topics}

{depth_topics_sql}

-- 4. Clear old questions for these topics so a re-run doesn't duplicate.
delete from questions_bank where topic_id in (
  {ids_sql}
);

-- 5. Questions ────────────────────────────────────────────────────────
{enr_qs}

{sea_qs}

{depth_qs_sql}
"""

open(os.path.join(SUP, 'content_pack.sql'), 'w', encoding='utf-8').write(out)
print('content_pack.sql written ·', len(DEPTH_Q), 'depth questions ·', len(all_ids), 'topics owned')
